"""Generate a self-contained Cloudflare Worker that serves a contract-driven mock of the bank's services.

    .venv/bin/python devtools/cf_mock/build_worker.py <contract.(json|yaml)> <behaviour.json> <outdir> [--name NAME] [--base-path /v1]

Same semantics as devtools/mock_service.py (the core is a JS port of it, devtools/cf_mock/core.js). The outdir gets worker.js (ES
module: the resolved contract operations + the behaviour file + the core + the Durable Object glue), wrangler.toml (free plan:
SQLite-backed Durable Object, no KV) and package.json. Static behaviour problems (mock_service `check`) are printed; --strict makes
them fatal. Each operation is served at its contract path from the root; --base-path also serves it under that prefix.
"""
import argparse
import json
import pathlib
import re
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "devtools"))

import mock_service as ms  # noqa: E402


def read_contract(path):
    p = pathlib.Path(path)
    if p.suffix.lower() in (".yaml", ".yml"):
        from builder.inputs import find_contract   # Ruby YAML.safe_load conversion, exactly as the builder reads it
        p = pathlib.Path(find_contract(p, tempfile.mkdtemp(prefix="cfmock-") + "/contract"))
    return json.loads(p.read_text(encoding="utf-8"))


def worker_config(contract, behaviour, base_path=""):
    ops = {}
    for key, op in ms.load_contract(contract).items():
        ops[key] = {k: v for k, v in op.items() if k != "path_regex"}
    base = ("/" + base_path.strip("/")) if base_path and base_path.strip("/") else ""
    return {"ops": ops, "behaviour": behaviour, "base_path": base}


def worker_source(config):
    core = (HERE / "core.js").read_text(encoding="utf-8")
    core = re.sub(r"(?m)^export (class|function|const|async function) ", r"\1 ", core)   # only the Worker entrypoints are exported
    glue = (HERE / "worker_glue.js").read_text(encoding="utf-8")
    cfg = json.dumps(config, ensure_ascii=False, indent=1).replace("</", "<\\/")
    return ("// GENERATED by devtools/cf_mock/build_worker.py - do not edit; regenerate from the contract and behaviour file.\n"
            f"const CONFIG = {cfg};\n\n{core}\n{glue}")


def wrangler_toml(name):
    return f'''name = "{name}"
main = "worker.js"
compatibility_date = "2024-11-01"
workers_dev = true

[[durable_objects.bindings]]
name = "MOCK_STATE"
class_name = "MockState"

[[migrations]]
tag = "v1"
new_sqlite_classes = ["MockState"]
'''


def build(contract_path, behaviour_path, outdir, name="bank-mock", base_path="", strict=False):
    contract = read_contract(contract_path)
    behaviour = json.loads(pathlib.Path(behaviour_path).read_text(encoding="utf-8"))
    problems = ms.Mock(contract, behaviour).check()
    for p in problems:
        print("  behaviour check:", p, file=sys.stderr)
    if strict and problems:
        raise SystemExit(f"{len(problems)} behaviour problem(s); fix them or drop --strict")
    out = pathlib.Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    config = worker_config(contract, behaviour, base_path)
    (out / "worker.js").write_text(worker_source(config), encoding="utf-8")
    (out / "wrangler.toml").write_text(wrangler_toml(name), encoding="utf-8")
    (out / "package.json").write_text(json.dumps({"name": name, "private": True, "type": "module"}, indent=1) + "\n")
    print(f"wrote {out}/worker.js ({len(config['ops'])} operations, {len(problems)} behaviour problem(s)), wrangler.toml, package.json")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("contract")
    ap.add_argument("behaviour")
    ap.add_argument("outdir")
    ap.add_argument("--name", default="bank-mock", help="Worker name -> https://<name>.<account>.workers.dev")
    ap.add_argument("--base-path", default="", help="also serve every operation under this prefix, e.g. /v1")
    ap.add_argument("--strict", action="store_true", help="fail on behaviour check problems")
    a = ap.parse_args(argv)
    if not re.fullmatch(r"[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?", a.name):
        ap.error("--name: lowercase letters, digits and dashes")
    build(a.contract, a.behaviour, a.outdir, a.name, a.base_path, a.strict)
    return 0


if __name__ == "__main__":
    sys.exit(main())
