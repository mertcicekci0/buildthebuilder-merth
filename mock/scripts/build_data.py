"""Generate mock/data.js from the case pack's test-customers.json.

Usage: python3 -I scripts/build_data.py "<case folder>/test-environment/test-customers.json" data.js

Each response body is stored as the raw JSON text Python re-serialises it to
(floats keep their "0.0" form), so the Worker returns it byte-for-byte
without re-encoding.
"""
import json
import sys


def entry(e):
    out = {"http": e["http"], "body": json.dumps(e["response"], ensure_ascii=False)}
    if "delaySeconds" in e:
        out["delay"] = e["delaySeconds"]
    return out


def main(src, dst):
    pack = json.load(open(src, encoding="utf-8"))
    customers, cards = {}, {}
    for cu in pack["customers"]:
        no = str(cu["customerNo"]).strip()
        s = cu["services"]
        customers[no] = {
            "cardsList": entry(s["cards.list"]),
            "contact": entry(s["contact.email.get"]) if "contact.email.get" in s else None,
            "pdf": entry(s["statement.pdf.send"]) if "statement.pdf.send" in s else None,
        }
        card_nos = set()
        for svc in ("cards.balance", "statement.week.get", "statement.week.decide", "statement.week.change"):
            card_nos.update(s.get(svc, {}).keys())
        for c in sorted(card_nos):
            if c in cards:
                raise SystemExit(f"duplicate card {c}")
            cards[c] = {
                "customerNo": no,
                "balance": entry(s["cards.balance"][c]) if c in s.get("cards.balance", {}) else None,
                "weekGet": entry(s["statement.week.get"][c]) if c in s.get("statement.week.get", {}) else None,
                "decide": {w: entry(v) for w, v in s.get("statement.week.decide", {}).get(c, {}).items()},
                "change": {w: entry(v) for w, v in s.get("statement.week.change", {}).get(c, {}).items()},
            }
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// GENERATED by scripts/build_data.py from test-environment/test-customers.json. Do not edit.\n")
        f.write("export default ")
        json.dump({"customers": customers, "cards": cards}, f, ensure_ascii=False, separators=(",", ":"))
        f.write(";\n")
    print(f"{len(customers)} customers, {len(cards)} cards -> {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
